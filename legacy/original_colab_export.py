# =====================================
# 9. Unsupervised Models
# =====================================

# --- Model 1: KMeans ---
kmeans = KMeans(n_clusters=3, random_state=42)
kmeans_labels = kmeans.fit_predict(X_scaled)

# --- Model 2: DBSCAN ---
dbscan = DBSCAN(eps=0.5, min_samples=5)
dbscan_labels = dbscan.fit_predict(X_scaled)

# --- Model 3: Hierarchical Clustering ---
hierarchical = AgglomerativeClustering(n_clusters=3)
hier_labels = hierarchical.fit_predict(X_scaled)


# =====================================
# 10. Attach cluster labels
# =====================================
results = df.copy()
results["kmeans_cluster"] = kmeans_labels
results["dbscan_cluster"] = dbscan_labels
results["hierarchical_cluster"] = hier_labels


print("Clustering complete!")
print("Target column dropped:", target_col)
results.head()

import matplotlib.pyplot as plt
from sklearn.decomposition import PCA

# =====================================
