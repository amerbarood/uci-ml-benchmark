# Add PCA columns to results for plotting
results['pca1'] = X_pca[:, 0]
results['pca2'] = X_pca[:, 1]


# =====================================
# 12. Plotting Function
# =====================================
def plot_clusters(df, cluster_col, title):
    plt.figure(figsize=(8, 6))
    unique_labels = df[cluster_col].unique()
    for label in unique_labels:
        subset = df[df[cluster_col] == label]
        plt.scatter(subset['pca1'], subset['pca2'], label=f'Cluster {label}', alpha=0.6)
    plt.xlabel('PCA 1')
    plt.ylabel('PCA 2')
    plt.title(title)
    plt.legend()
    plt.show()


# =====================================
# 13. Visualize Each Clustering Result
