    print(f"Processing: {file_name}")
    print("="*80)

    # ---------------------------------
    # Load CSV
    # ---------------------------------
    try:
        df = pd.read_csv(file_path, sep=';', encoding='utf-8')
    except UnicodeDecodeError:
        # If UTF-8 fails, try a common alternative like 'latin1'
        df = pd.read_csv(file_path, sep=';', encoding='latin1')

    # ---------------------------------
